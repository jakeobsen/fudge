// Lists the runtime exports of @raycast/api from the vendored type
// definitions and writes them to src/api/raycast-exports.generated.ts.
//
//   node scripts/raycast-exports.ts          write the file
//   node scripts/raycast-exports.ts --check  fail if the file is out of date

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const typesPath = fileURLToPath(new URL("../vendor/raycast-api/index.d.ts", import.meta.url));
const outputPath = fileURLToPath(new URL("../src/api/raycast-exports.generated.ts", import.meta.url));

/** Every exported value: consts, functions, classes, enums and namespaces (which may hold values). */
export function raycastExports(types: string): string[] {
    const names = new Set<string>();
    for (const match of types.matchAll(/^ ?export declare (?:const|function|class|enum|namespace) (\w+)/gm)) {
        names.add(match[1]!);
    }
    return [...names].sort();
}

export function render(names: readonly string[]): string {
    return [
        "// Generated by scripts/raycast-exports.ts from vendor/raycast-api/index.d.ts. Don't edit.",
        "",
        "export const RAYCAST_EXPORTS: readonly string[] = [",
        ...names.map((name) => `    ${JSON.stringify(name)},`),
        "];",
        "",
    ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const expected = render(raycastExports(readFileSync(typesPath, "utf8")));
    if (process.argv.includes("--check")) {
        if (readFileSync(outputPath, "utf8") !== expected) {
            console.error("src/api/raycast-exports.generated.ts is out of date: run `npm run generate`");
            process.exit(1);
        }
    } else {
        writeFileSync(outputPath, expected);
    }
}
