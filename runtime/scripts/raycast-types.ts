// Derives two files from Raycast's type definitions and their version (vendor/raycast-api/):
//
//   src/api/raycast-exports.generated.ts  the @raycast/api version and the names of its runtime exports
//   src/api/raycast-enums.generated.ts    the members and values of its enums (Icon, Color, …)
//
// Run it with `npm run generate`; `make raycast-types` does so after updating the
// type definitions. `npm run typecheck` runs it with --check, which fails if
// either file is out of date.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const typesPath = fileURLToPath(new URL("../vendor/raycast-api/index.d.ts", import.meta.url));
const versionPath = fileURLToPath(new URL("../vendor/raycast-api/VERSION", import.meta.url));
const exportsPath = fileURLToPath(new URL("../src/api/raycast-exports.generated.ts", import.meta.url));
const enumsPath = fileURLToPath(new URL("../src/api/raycast-enums.generated.ts", import.meta.url));
const header = "// Generated by scripts/raycast-types.ts from vendor/raycast-api/index.d.ts. Don't edit.";

/** Every exported value: consts, functions, classes, enums and namespaces (which may hold values). */
export function raycastExports(types: string): string[] {
    const names = new Set<string>();
    for (const match of types.matchAll(/^ ?export declare (?:const|function|class|enum|namespace) (\w+)/gm)) {
        names.add(match[1]!);
    }
    return [...names].sort();
}

export type Enums = Record<string, Record<string, string | number>>;

/** Every enum, exported or not (`Action.Style` is the unexported `ActionStyle`), with its members' values. */
export function raycastEnums(types: string): Enums {
    const code = types.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
    const enums: Enums = {};
    for (const match of code.matchAll(/declare enum (\w+)\s*\{([^}]*)\}/g)) {
        const members: Record<string, string | number> = {};
        let next = 0;
        for (const entry of match[2]!.split(",")) {
            const member = entry.trim().match(/^(\w+)\s*(?:=\s*("(?:[^"\\]|\\.)*"|-?\d+))?$/);
            if (!member) continue;
            const literal = member[2];
            const value = literal === undefined ? next : literal.startsWith('"') ? (JSON.parse(literal) as string) : Number(literal);
            if (typeof value === "number") next = value + 1;
            members[member[1]!] = value;
        }
        enums[match[1]!] = members;
    }
    return enums;
}

export function renderExports(names: readonly string[], version: string): string {
    return [
        header,
        "",
        `export const RAYCAST_API_VERSION = ${JSON.stringify(version)};`,
        "",
        "export const RAYCAST_EXPORTS: readonly string[] = [",
        ...names.map((name) => `    ${JSON.stringify(name)},`),
        "];",
        "",
    ].join("\n");
}

export function vendoredVersion(): string {
    return readFileSync(versionPath, "utf8").trim();
}

export function renderEnums(enums: Enums): string {
    const lines = [header, "", "export const RAYCAST_ENUMS = {"];
    for (const name of Object.keys(enums).sort()) {
        lines.push(`    ${name}: {`);
        for (const [member, value] of Object.entries(enums[name]!)) lines.push(`        ${member}: ${JSON.stringify(value)},`);
        lines.push("    },");
    }
    lines.push("} as const;", "");
    return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const types = readFileSync(typesPath, "utf8");
    const outputs = [
        [exportsPath, renderExports(raycastExports(types), vendoredVersion())],
        [enumsPath, renderEnums(raycastEnums(types))],
    ] as const;
    if (process.argv.includes("--check")) {
        const stale = outputs.filter(([path, expected]) => readFileSync(path, "utf8") !== expected);
        for (const [path] of stale) console.error(`${path.replace(/.*\/runtime\//, "")} is out of date: run \`npm run generate\``);
        if (stale.length > 0) process.exit(1);
    } else {
        for (const [path, content] of outputs) writeFileSync(path, content);
    }
}
