import Foundation

// `Clipboard.paste()` and `Action.Paste`. The logic lives here; the app supplies the pasteboard, the Accessibility
// check and key events through the protocols in Selection.swift and below, and tests supply fakes.

/// Why a paste failed. `description` is the message the extension's promise rejects with.
public enum PasteError: Error, Equatable, Sendable, CustomStringConvertible {
    case accessibilityNeeded
    case noTarget

    public var description: String {
        switch self {
        case .accessibilityNeeded:
            "fudge needs Accessibility permission to paste. The content was copied instead; allow fudge in System "
                + "Settings → Privacy & Security → Accessibility."
        case .noTarget:
            "There is no app to paste into"
        }
    }
}

/// Posts the paste shortcut.
@MainActor
public protocol PasteKeyPoster: AnyObject {
    /// Posts ⌘V, key down then key up, to the application `pid`.
    func postPaste(to pid: Int32)
}

extension PasteboardContents {
    /// The types clipboard managers that follow nspasteboard.org skip: fudge's own write, there only to be pasted.
    public static let transientType = "org.nspasteboard.TransientType"
    public static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"

    /// What `Clipboard.paste` puts on the pasteboard: the content as `Clipboard.copy` writes it (text, HTML, a file),
    /// in one item, marked transient and auto-generated.
    public static func forPaste(text: String?, html: String?, file: String?) -> PasteboardContents {
        var item: [Representation] = []
        func add(_ type: String, _ string: String) { item.append(Representation(type: type, data: Data(string.utf8))) }
        if let file {
            add("public.file-url", URL(fileURLWithPath: file).absoluteString)
            if text == nil { add("public.utf8-plain-text", file) }
        }
        if let html { add("public.html", html) }
        if let text { add("public.utf8-plain-text", text) }
        add(transientType, "")
        add(autoGeneratedType, "")
        return PasteboardContents(items: [item])
    }
}

/// Pastes into the app the user is in: writes the content to the pasteboard, hides fudge's panel if asked, posts ⌘V
/// to the frontmost app, and puts the user's clipboard back about a second later, unless something else has changed
/// it by then.
@MainActor
public final class Paste {
    private let gate: AccessibilityGate
    private let keys: any PasteKeyPoster
    private let pasteboard: any PasteboardAccess
    private let ownPid: Int32
    private let restoreDelay: Duration

    /// The restore waiting to happen: the user's clipboard from before the first of the pastes in quick succession,
    /// and the task that writes it back.
    private var pending: (snapshot: PasteboardContents, task: Task<Void, Never>)?

    public init(
        gate: AccessibilityGate,
        keys: any PasteKeyPoster,
        pasteboard: any PasteboardAccess,
        ownPid: Int32,
        restoreDelay: Duration = .seconds(1)
    ) {
        self.gate = gate
        self.keys = keys
        self.pasteboard = pasteboard
        self.ownPid = ownPid
        self.restoreDelay = restoreDelay
    }

    /// Pastes `content`. With `closeMainWindow`, `hideWindow` hides fudge's panel and returns once it's really gone,
    /// so key status is back with the target app. `frontmost` is read after that. Resolves once ⌘V is posted; the
    /// restore follows on its own.
    public func paste(
        _ content: PasteboardContents,
        closeMainWindow: Bool,
        hideWindow: () async -> Void,
        frontmost: () -> FrontmostApplication?
    ) async throws {
        // While a restore is pending, the pasteboard holds fudge's own last write: keep the snapshot from before it.
        let snapshot = pending?.snapshot ?? SelectedText.restoration(of: pasteboard.contents())
        pending?.task.cancel()
        pending = nil
        pasteboard.replace(with: content)
        let written = pasteboard.changeCount

        // Without permission the content stays on the pasteboard, so the user can paste it themselves.
        guard gate.isTrusted() else { throw PasteError.accessibilityNeeded }
        if closeMainWindow { await hideWindow() }
        guard let target = frontmost(), target.pid != ownPid else {
            restore(snapshot, ifStill: written)
            throw PasteError.noTarget
        }
        keys.postPaste(to: target.pid)
        let delay = restoreDelay
        let task = Task { [weak self] in
            try? await Task.sleep(for: delay)
            guard !Task.isCancelled, let self else { return }
            self.restore(snapshot, ifStill: written)
            self.pending = nil
        }
        pending = (snapshot, task)
    }

    /// Writes `snapshot` back, if the pasteboard still holds fudge's write: if the user or an app has changed it
    /// since, theirs stays. A concealed snapshot was emptied by `SelectedText.restoration`, which clears it.
    private func restore(_ snapshot: PasteboardContents, ifStill written: Int) {
        guard pasteboard.changeCount == written else { return }
        pasteboard.replace(with: snapshot)
    }
}
