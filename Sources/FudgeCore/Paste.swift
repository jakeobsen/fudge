import Foundation

// `Clipboard.paste()` and `Action.Paste`. The logic lives here; the app supplies the pasteboard, the Accessibility
// check and key events through the protocols in Selection.swift and below, and tests supply fakes.

/// Why a paste failed. `description` is the message the extension's promise rejects with.
public enum PasteError: Error, Equatable, Sendable, CustomStringConvertible {
    case accessibilityNeeded
    case noTarget
    /// A protected password field (secure input) had the keyboard when an expansion's turn came: nothing was posted.
    case secureInput

    public var description: String {
        switch self {
        case .accessibilityNeeded:
            "Fudge needs Accessibility permission to paste. The content was copied instead; allow Fudge in System "
                + "Settings → Privacy & Security → Accessibility."
        case .noTarget:
            "There is no app to paste into"
        case .secureInput:
            "A protected password field has the keyboard, so nothing was pasted"
        }
    }
}

/// Posts the paste shortcut, and the ← presses that put the caret where a snippet's `{cursor}` was.
@MainActor
public protocol PasteKeyPoster: AnyObject {
    /// Posts ⌘V, key down then key up, to the application `pid`.
    func postPaste(to pid: Int32)
    /// Posts ←, key down then key up, `count` times, to the application `pid`.
    func postLeftArrow(_ count: Int, to pid: Int32)
    /// Posts ⌫, key down then key up, `count` times, to the application `pid`: an expanded keyword's characters.
    func postDelete(_ count: Int, to pid: Int32)
}

extension PasteboardContents {
    /// The types clipboard managers that follow nspasteboard.org skip: fudge's own write, there only to be pasted.
    public static let transientType = "org.nspasteboard.TransientType"
    public static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"

    /// What `Clipboard.paste` puts on the pasteboard: the content as `Clipboard.copy` writes it (text, HTML, a file),
    /// in one item, marked transient and auto-generated.
    public static func forPaste(text: String?, html: String?, file: String?) -> PasteboardContents {
        var item: [Representation] = []
        func add(_ type: String, _ string: String) { item.append(Representation(type: type, data: Data(string.utf8))) }
        if let file {
            add("public.file-url", URL(fileURLWithPath: file).absoluteString)
            if text == nil { add("public.utf8-plain-text", file) }
        }
        if let html { add("public.html", html) }
        if let text { add("public.utf8-plain-text", text) }
        add(transientType, "")
        add(autoGeneratedType, "")
        return PasteboardContents(items: [item])
    }
}

/// Pastes into the app the user is in: writes the content to the pasteboard, hides fudge's panel if asked, posts ⌘V
/// to the frontmost app, and puts the user's clipboard back about a second later, unless something else has changed
/// it by then.
@MainActor
public final class Paste {
    private let gate: AccessibilityGate
    private let keys: any PasteKeyPoster
    private let pasteboard: any PasteboardAccess
    private let ownPid: Int32
    private let restoreDelay: Duration
    /// Shared with `SelectedText`'s ⌘C fallback. Pastes take turns with each other and with it: one taking its
    /// snapshot while another's content is on the pasteboard would keep fudge's write as the user's clipboard.
    private let turns: PasteboardTurns

    /// The restore waiting to happen: the user's clipboard from before the first of the pastes in quick succession,
    /// the `changeCount` of fudge's write that it replaces, and the task that writes it back. The turns know about
    /// the task, so the fallback can wait for it.
    private var pending: (snapshot: PasteboardContents, written: Int, task: Task<Void, Never>)? {
        didSet { turns.restore = pending?.task }
    }

    public init(
        gate: AccessibilityGate,
        keys: any PasteKeyPoster,
        pasteboard: any PasteboardAccess,
        ownPid: Int32,
        turns: PasteboardTurns,
        restoreDelay: Duration = .seconds(1)
    ) {
        self.gate = gate
        self.keys = keys
        self.pasteboard = pasteboard
        self.ownPid = ownPid
        self.turns = turns
        self.restoreDelay = restoreDelay
    }

    /// Pastes `content`. With `closeMainWindow`, `hideWindow` hides fudge's panel and returns once it's really gone,
    /// so key status is back with the target app. `frontmost` is read after that. Resolves once ⌘V is posted; the
    /// restore follows on its own. A paste that starts while another paste or a ⌘C fallback is running waits for it.
    /// It doesn't wait for a pending restore: it keeps that restore's snapshot instead. `backspaces` ⌫ presses go to
    /// the same app just before ⌘V, deleting an expanded keyword, and `leftArrows` ← presses follow it, so the caret
    /// ends up where a snippet's `{cursor}` was.
    public func paste(
        _ content: PasteboardContents,
        closeMainWindow: Bool,
        origin: CallOrigin,
        backspaces: Int = 0,
        leftArrows: Int = 0,
        hideWindow: () async -> Void,
        frontmost: () -> FrontmostApplication?
    ) async throws {
        try await turns.run {
            try await pasteNow(
                content, closeMainWindow: closeMainWindow, origin: origin, backspaces: backspaces,
                leftArrows: leftArrows, hideWindow: hideWindow, secureInput: { false }, frontmost: frontmost)
        }
    }

    /// Expands a snippet's keyword (SPEC-078 B): `backspaces` ⌫ presses, ⌘V and `leftArrows` ← presses go only to
    /// `target`, the app the keyword was typed in (its key event's target), never to the frontmost app when that's
    /// another one, such as the app under Spotlight's or another launcher's panel. Nothing is posted when the target
    /// is unknown or Fudge itself, or when `secureInput` says a protected password field has the keyboard by the time the
    /// paste's turn comes (it may wait on a ⌘C fallback); the clipboard is put back then.
    public func expand(
        _ content: PasteboardContents,
        target: Int32?,
        backspaces: Int,
        leftArrows: Int,
        secureInput: () -> Bool
    ) async throws {
        try await turns.run {
            try await pasteNow(
                content, closeMainWindow: false, origin: .background, backspaces: backspaces,
                leftArrows: leftArrows, hideWindow: {}, secureInput: secureInput,
                frontmost: { target.map { FrontmostApplication(pid: $0, bundleIdentifier: nil) } })
        }
    }

    private func pasteNow(
        _ content: PasteboardContents,
        closeMainWindow: Bool,
        origin: CallOrigin,
        backspaces: Int,
        leftArrows: Int,
        hideWindow: () async -> Void,
        secureInput: () -> Bool,
        frontmost: () -> FrontmostApplication?
    ) async throws {
        // While a restore is pending and the pasteboard still holds fudge's own last write, keep the snapshot from
        // before it. If the user or an app has copied since, that's the clipboard to put back.
        let snapshot =
            pending.flatMap { $0.written == pasteboard.changeCount ? $0.snapshot : nil }
            ?? SelectedText.restoration(of: pasteboard.contents())
        pending?.task.cancel()
        pending = nil
        pasteboard.replace(with: content)
        let written = pasteboard.changeCount
        turns.markOwn(written)

        // Without permission the content stays on the pasteboard, so the user can paste it themselves.
        guard gate.isTrusted(origin: origin) else { throw PasteError.accessibilityNeeded }
        if closeMainWindow { await hideWindow() }
        guard let target = frontmost(), target.pid != ownPid else {
            restore(snapshot, ifStill: written)
            throw PasteError.noTarget
        }
        guard !secureInput() else {
            restore(snapshot, ifStill: written)
            throw PasteError.secureInput
        }
        if backspaces > 0 { keys.postDelete(backspaces, to: target.pid) }
        keys.postPaste(to: target.pid)
        if leftArrows > 0 { keys.postLeftArrow(leftArrows, to: target.pid) }
        let delay = restoreDelay
        let task = Task { [weak self] in
            try? await Task.sleep(for: delay)
            guard !Task.isCancelled, let self else { return }
            self.restore(snapshot, ifStill: written)
            self.pending = nil
        }
        pending = (snapshot, written, task)
    }

    /// Writes `snapshot` back, if the pasteboard still holds fudge's write: if the user or an app has changed it
    /// since, theirs stays. A concealed snapshot was emptied by `SelectedText.restoration`, which clears it.
    private func restore(_ snapshot: PasteboardContents, ifStill written: Int) {
        guard pasteboard.changeCount == written else { return }
        pasteboard.replace(with: snapshot)
        turns.markOwn(pasteboard.changeCount)
    }
}
