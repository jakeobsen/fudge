    public static func symbol(for icon: String) -> String? {
        guard icon.hasSuffix("-16") else { return nil }
        let name = String(icon.dropLast(3))
        if name.hasPrefix("number-"), let number = Int(name.dropFirst("number-".count)) {
            // SF Symbols has numbered squares up to 50.
            return number <= 50 ? String(format: "%02d.square", number) : "number.square"
        }
        return symbols[name]
    }

